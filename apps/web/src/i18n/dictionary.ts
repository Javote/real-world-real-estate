export type TranslationKey = keyof typeof esAR

export type Diccionario = Record<TranslationKey, string>

const cargados: Partial<Record<Locale, Diccionario>> = { 'es-AR': esAR }

export function diccionarioCargado(locale: Locale): Diccionario | undefined {
  return cargados[locale]
}

export async function cargarDiccionario(locale: Locale): Promise<Diccionario> {
  const cargado = cargados[locale]
  if (cargado) return cargado
  const { enUS } = await import('./en-US')
  cargados['en-US'] = enUS
  return enUS
}
